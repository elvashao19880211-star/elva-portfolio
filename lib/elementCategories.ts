// 自动分类函数：遍历关键词，匹配到即归类
export function getElementCategory(element: string): ElementCategory | null {
  for (const [keyword, cat] of Object.entries(CATEGORY_KEYWORDS)) {
    if (element.includes(keyword)) return cat;
  }
  return null; // 未匹配
}

// 对整组元素分类
export function groupElementsByCategory(elements: string[]): Record<ElementCategory, string[]> {
  const groups: Record<ElementCategory, string[]> = {
    '鸟兽鱼虫': [],
    '花草植物': [],
    '几何符号': [],
    '人物': [],
    '器物博古': [],
  };
  for (const e of elements) {
    const cat = getElementCategory(e);
    if (cat) groups[cat].push(e);
  }
  return groups;
}
