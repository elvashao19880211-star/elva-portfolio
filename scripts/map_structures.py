"""
将现有结构值映射到新分类体系：
- L1: 单独纹样 | 二方连续 | 四方连续
- L2: 
  单独纹样 → 自由纹样 | 适合纹样 | 角隅纹样
  二方连续 → 散点式 | 直立式 | 波线式 | 折线式 | 综合式
  四方连续 → 散点式 | 连缀式 | 重叠式
"""

import re, json

def classify_structure(raw: str):
    """将原结构值映射为 (L1, L2)"""
    if not raw:
        return ('单独纹样', '自由纹样')
    
    v = raw.strip()
    
    # 四方连续
    if v.startswith('四方连续'):
        rest = v.replace('四方连续', '').lstrip('/').lstrip()
        # 取第一个空格前的部分（处理 "网格连缀  二方连续/..." 这种合并表达）
        first_part = rest.split('  ')[0].split('  ')[0].strip()
        
        if any(kw in first_part for kw in ['散点', '错位散点', '不规则散点', '规则散点', '单散点']):
            return ('四方连续', '散点式')
        if '重叠' in first_part:
            return ('四方连续', '重叠式')
        # 各种连缀
        return ('四方连续', '连缀式')
    
    # 二方连续
    if v.startswith('二方连续'):
        rest = v.replace('二方连续', '').lstrip('/').lstrip()
        first_part = rest.split('  ')[0].split('  ')[0].strip()
        
        if any(kw in first_part for kw in ['散点', '单散点']):
            return ('二方连续', '散点式')
        if '波线' in first_part:
            return ('二方连续', '波线式')
        if '直立' in first_part:
            return ('二方连续', '直立式')
        if '折线' in first_part:
            return ('二方连续', '折线式')
        if '综合' in first_part:
            return ('二方连续', '综合式')
        return ('二方连续', '散点式')
    
    # 适合 → 单独纹样/适合纹样
    if v.startswith('适合'):
        return ('单独纹样', '适合纹样')
    
    # 单独
    if v.startswith('单独'):
        # 提取整个结构描述
        if '角隅' in v and '适合' not in v:
            return ('单独纹样', '角隅纹样')
        if '适合' in v:
            return ('单独纹样', '适合纹样')
        if '角隅' in v:
            return ('单独纹样', '角隅纹样')
        return ('单独纹样', '自由纹样')
    
    # 独立值
    if '自由' in v:
        return ('单独纹样', '自由纹样')
    if '适合' in v:
        return ('单独纹样', '适合纹样')
    if '角隅' in v:
        return ('单独纹样', '角隅纹样')
    
    # 造型类、团窠 → 单独/自由
    return ('单独纹样', '自由纹样')

